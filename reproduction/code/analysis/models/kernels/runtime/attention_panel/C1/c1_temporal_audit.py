def matrices(frame, numeric, global_x, fit, test, mode):
    if mode == "legacy_replay":
        return (
            global_x[fit],
            global_x[test],
            {"unknown_test_categories": 0, "vocabulary": "global_legacy"},
        )
    values = frame["sw1_industry"].fillna("<MISSING>").astype(str)
    categories = sorted(values.iloc[fit].unique().tolist())
    lookup = {v: i for i, v in enumerate(categories)}
    a = values.iloc[fit].map(lookup).to_numpy(np.float32)
    b = values.iloc[test].map(lookup).to_numpy(np.float32)
    return (
        np.column_stack([numeric[fit], a]),
        np.column_stack([numeric[test], b]),
        {
            "unknown_test_categories": int(np.isnan(b).sum()),
            "vocabulary_n": len(categories),
            "vocabulary": "fit_only",
        },
    )


def make_model(mode, seed, classify=False):
    m = legacy.classifier(seed) if classify else legacy.regressor(seed)
    if mode != "legacy_replay":
        m.set_params(early_stopping=False, max_iter=80)
    return m


def residual(frame, numeric, gx, target, folds, mode, offset):
    target = np.asarray(target, float)
    out = np.full(len(frame), np.nan, dtype=np.float32)
    diag = []
    for fold, train, test in folds:
        train = train[np.isfinite(target[train])]
        test = test[np.isfinite(target[test])]
        d = {"fold_id": fold, "train_rows": len(train), "test_rows": len(test)}
        if len(train) < 1000 or len(test) < 100:
            diag.append({**d, "status": "insufficient"})
            continue
        fit = u.deterministic_thin(train, 30000)
        a, b, meta = matrices(frame, numeric, gx, fit, test, mode)
        m = make_model(mode, legacy.SEED + offset + fold)
        m.fit(a, target[fit])
        pred = m.predict(b)
        out[test] = (target[test] - pred).astype(np.float32)
        diag.append(
            {
                **d,
                **meta,
                "status": "estimated",
                "train_fit_rows": len(fit),
                "model_iterations": m.n_iter_,
            }
        )
    return out, diag


def dose_array(values, dates, mode):
    values = pd.to_numeric(values, errors="coerce")
    finite = values[np.isfinite(values)]
    calibration = (
        (dates < CALIBRATION_END)
        if mode != "legacy_replay"
        else pd.Series(True, index=values.index)
    )
    eligible = values.where(calibration)
    usable = eligible[np.isfinite(eligible)]
    cd = int(dates[calibration & values.notna() & np.isfinite(values)].nunique())
    if len(usable) < 1000 or cd < 20:
        return np.full(len(values), np.nan), {
            "status": "DEFERRED_NO_PAST_CALIBRATION",
            "calibration_rows": len(usable),
            "calibration_dates": cd,
            "scale": None,
        }
    lo, hi = float(usable.quantile(0.01)), float(usable.quantile(0.99))
    central = values.where(values.between(lo, hi, inclusive="both"))
    centered = central - central.groupby(dates, observed=True).transform("mean")
    scale = float(centered[calibration].std(ddof=0))
    if not np.isfinite(scale) or scale < 1e-12:
        raise ValueError("Invalid prespecified calibration scale")
    return (centered / scale).to_numpy(float), {
        "status": "CALIBRATED",
        "calibration_rows": len(usable),
        "calibration_dates": cd,
        "calibration_end_exclusive": (
            str(CALIBRATION_END) if mode != "legacy_replay" else "full_sample_legacy"
        ),
        "p01": lo,
        "p99": hi,
        "scale": scale,
        "retained_rows": int(central.notna().sum()),
    }


def psi_estimate(psi, dates, h):
    ok = np.isfinite(psi)
    v = psi[ok]
    d = dates[ok]
    theta = float(v.mean()) if len(v) else math.nan
    score = pd.Series(v - theta).groupby(d.to_numpy(), sort=True).sum()
    meat = (
        float(u.hac_meat(score.to_numpy(float), u.horizon_hac_lag(h))[0, 0])
        if len(score)
        else math.nan
    )
    se = (
        math.sqrt(max(meat, 0.0)) / len(v) if len(v) and np.isfinite(meat) else math.nan
    )
    t = theta / se if se > 0 else math.nan
    return {
        "coefficient": theta,
        "se_hac": se,
        "ci95_low": theta - 1.959963984540054 * se,
        "ci95_high": theta + 1.959963984540054 * se,
        "t_hac": t,
        "p_two_sided_hac": u.normal_two_sided_p(t),
        "n_rows": int(ok.sum()),
        "n_dates": int(d.nunique()),
        "hac_lag_sample_dates": u.horizon_hac_lag(h),
    }


def aipw(frame, numeric, gx, y, w, folds, mode, h, offset):
    out = np.full(len(y), np.nan)
    diag = []
    for fold, train, test in folds:
        train = train[np.isfinite(y[train]) & np.isfinite(w[train])]
        test = test[np.isfinite(y[test]) & np.isfinite(w[test])]
        t0 = train[w[train] == 0]
        t1 = train[w[train] == 1]
        e0 = test[w[test] == 0]
        e1 = test[w[test] == 1]
        d = {
            "fold_id": fold,
            "train0": len(t0),
            "train1": len(t1),
            "test0": len(e0),
            "test1": len(e1),
            "test_rows": len(test),
        }
        if min(len(t0), len(t1), len(e0), len(e1)) < 1000:
            diag.append({**d, "status": "insufficient"})
            continue
        f0 = u.deterministic_thin(t0, 15000)
        f1 = u.deterministic_thin(t1, 15000)
        fit = np.sort(np.concatenate([f0, f1]))
        weights = np.where(w[fit] == 1, len(t1) / len(f1), len(t0) / len(f0))
        a, b, meta = matrices(frame, numeric, gx, fit, test, mode)
        m = make_model(mode, legacy.SEED + offset + fold, True)
        m.fit(a, w[fit].astype(int), sample_weight=weights)
        raw = m.predict_proba(b)[:, 1]
        mus = []
        unknown = meta["unknown_test_categories"]
        for shift, f in [(100, f0), (200, f1)]:
            a, b, meta2 = matrices(frame, numeric, gx, f, test, mode)
            unknown += meta2["unknown_test_categories"]
            r = make_model(mode, legacy.SEED + offset + shift + fold)
            r.fit(a, y[f])
            mus.append(r.predict(b))
        mu0, mu1 = mus
        p = np.clip(raw, 0.05, 0.95)
        wt = w[test]
        yt = y[test]
        out[test] = mu1 - mu0 + wt * (yt - mu1) / p - (1 - wt) * (yt - mu0) / (1 - p)
        clip = int(((raw < 0.05) | (raw > 0.95)).sum())
        diag.append(
            {
                **d,
                "status": "estimated",
                "fit0": len(f0),
                "fit1": len(f1),
                "propensity_clipped_rows": clip,
                "propensity_clipped_fraction": clip / len(test),
                "unknown_test_categories_all_models": unknown,
                "weighted_prior_restore_error": float(
                    abs(
                        weights[w[fit] == 1].sum() / weights.sum()
                        - len(t1) / len(train)
                    )
                ),
            }
        )
    est = psi_estimate(out, frame.signal_date, h)
    ed = [d for d in diag if d["status"] == "estimated"]
    n = sum(d["test_rows"] for d in ed)
    est["pooled_propensity_clipped_fraction"] = (
        sum(d["propensity_clipped_rows"] for d in ed) / n if n else math.nan
    )
    est["max_fold_propensity_clipped_fraction"] = max(
        (d["propensity_clipped_fraction"] for d in ed), default=math.nan
    )
    return out, est, diag


def all_folds(ds):
    return len(ds) == 6 and all(x["status"] == "estimated" for x in ds)


def full_est(d, y, dates, h):
    z = u.orthogonal_univariate(d, y, dates, u.horizon_hac_lag(h))
    for k in [
        "coefficient",
        "se_hac",
        "ci95_low",
        "ci95_high",
        "t_hac",
        "p_two_sided_hac",
    ]:
        z.setdefault(k, math.nan)
    return z


def finalize(rows, kind):
    df = pd.DataFrame(rows)
    df["multiplicity_family"] = (
        ("tree_dml_3features_x_8H|" + df.lens + "|" + df.exposure_group)
        if kind == "dml"
        else ("tree_aipw_4states_x_8H|" + df.lens)
    )
    df = u.add_multiplicity_fail_closed(df, ["multiplicity_family"])
    df["simultaneous_z"] = np.where(
        df.estimability_status.eq("COMPLETE"), legacy.SIMULTANEOUS_Z, np.nan
    )
    df["simul95_low"] = df.coefficient - legacy.SIMULTANEOUS_Z * df.se_hac
    df["simul95_high"] = df.coefficient + legacy.SIMULTANEOUS_Z * df.se_hac
    df["simultaneous_method"] = (
        "Bonferroni over 8H per exposure/state, not all families"
    )
    return df


def run_lens(lens):
    if not (AUDIT / "frozen_design.json").exists():
        raise RuntimeError("Freeze first")
    if (AUDIT / f"complete_{lens}.json").exists():
        raise FileExistsError("Refusing to overwrite complete lens")
    started = time.time()
    log(f"LOAD {lens}")
    cols = {
        "lens",
        "signal_date",
        "stock_code",
        "sw1_industry",
        *legacy.CONTROLS,
        *legacy.EXPOSURES,
        *legacy.STATE_COLUMNS.values(),
        *[f"price_excess_{h}" for h in H],
        *[f"open_exit_date_{h}" for h in H],
        *[f"attention_target_date_{h}" for h in H],
    }
    frame = pd.read_parquet(PANEL, columns=sorted(cols), filters=[("lens", "==", lens)])
    frame.signal_date = pd.to_datetime(frame.signal_date)
    frame.sort_values(["signal_date", "stock_code"], kind="mergesort", inplace=True)
    frame.reset_index(drop=True, inplace=True)
    gx, _ = legacy.model_x(frame)
    numeric = gx[:, : len(legacy.CONTROLS)].copy()
    base = u.fold_masks(frame.signal_date, pd.read_csv(FOLDS))
    purged = {}
    purges = []
    assert min(frame.iloc[t].signal_date.min() for _, _, t in base) == CALIBRATION_END
    for h in H:
        purged[h], a = legacy.purged_folds(frame, base, h, lens)
        purges += a
    assert all(a["target_strictly_before_test"] for a in purges)
    pd.DataFrame(purges).to_csv(AUDIT / f"purge_{lens}.csv", index=False)
    states = legacy.build_states(frame)
    saved = {}
    fits = []
    calibrations = []
    allresults = {}
    for mode in MODES:
        log(f"START {lens} {mode} doses")
        dr = {}
        ds = {}
        scales = {}
        yr = {}
        ys = {}
        ps = {}
        drows = []
        arows = []
        doseout = frame[["signal_date", "stock_code"]].copy()
        for i, ex in enumerate(legacy.EXPOSURES):
            dose, cal = dose_array(frame[ex], frame.signal_date, mode)
            scales[ex] = cal["scale"]
            calibrations.append({"lens": lens, "mode": mode, "exposure": ex, **cal})
            dr[ex], ds[ex] = residual(frame, numeric, gx, dose, base, mode, 1000 * i)
            doseout[ex] = dr[ex]
            fits += [
                {
                    "lens": lens,
                    "mode": mode,
                    "module": "DML",
                    "role": "dose",
                    "variable": ex,
                    "H": 0,
                    **x,
                }
                for x in ds[ex]
            ]
        doseout.to_parquet(DATA / f"dose_residuals_{lens}_{mode}.parquet", index=False)
        for h in H:
            log(f"{lens} {mode} H{h} outcome+AIPW")
            y = pd.to_numeric(frame[f"price_excess_{h}"], errors="coerce").to_numpy(
                float
            )
            yr[h], ys[h] = residual(frame, numeric, gx, y, purged[h], mode, 100000 + h)
            fits += [
                {
                    "lens": lens,
                    "mode": mode,
                    "module": "DML",
                    "role": "outcome",
                    "variable": "price_excess",
                    "H": h,
                    **x,
                }
                for x in ys[h]
            ]
            out = frame[["signal_date", "stock_code"]].copy()
            out["outcome_residual"] = yr[h]
            for ex in legacy.EXPOSURES:
                e = full_est(dr[ex], yr[h], frame.signal_date, h)
                complete = (
                    e["n_rows"] >= 10000
                    and e["n_dates"] >= 100
                    and all_folds(ds[ex])
                    and all_folds(ys[h])
                )
                drows.append(
                    {
                        "lens": lens,
                        "mode": mode,
                        "exposure": ex,
                        "exposure_group": (
                            "own" if ex.startswith("own_") else "CategoryShare"
                        ),
                        "holding_h": h,
                        **e,
                        "estimability_status": (
                            "COMPLETE"
                            if complete
                            else "DEFERRED_INCOMPLETE_TIME_FOLDS_OR_CALIBRATION"
                        ),
                        "dose_scale": scales[ex],
                    }
                )
            for i, (state, w) in enumerate(states.items()):
                p, e, diag = aipw(
                    frame,
                    numeric,
                    gx,
                    y,
                    w,
                    purged[h],
                    mode,
                    h,
                    1000000 + i * 10000 + h,
                )
                ps[(state, h)] = p
                out[state] = p
                fits += [
                    {
                        "lens": lens,
                        "mode": mode,
                        "module": "AIPW",
                        "role": "joint",
                        "variable": state,
                        "H": h,
                        **x,
                    }
                    for x in diag
                ]
                support = e["n_rows"] >= 10000 and e["n_dates"] >= 100
                overlap = (
                    np.isfinite(e["pooled_propensity_clipped_fraction"])
                    and e["pooled_propensity_clipped_fraction"] <= 0.20
                )
                timegate = all_folds(diag)
                arows.append(
                    {
                        "lens": lens,
                        "mode": mode,
                        "state_contrast": state,
                        "holding_h": h,
                        **e,
                        "support_gate_pass": support,
                        "overlap_gate_pass": overlap,
                        "all_time_folds_pass": timegate,
                        "estimability_status": (
                            "COMPLETE"
                            if support and overlap and timegate
                            else "DEFERRED_SUPPORT_OVERLAP_OR_TIME_FOLD_GATE"
                        ),
                    }
                )
            out.to_parquet(
                DATA / f"outcomes_psi_{lens}_{mode}_H{h}.parquet", index=False
            )
        for kind, rows in [("dml", drows), ("aipw", arows)]:
            result = finalize(rows, kind)
            result.to_csv(DATA / f"{kind}_{lens}_{mode}.csv", index=False)
            allresults[(mode, kind)] = result
        saved[mode] = {"d": dr, "y": yr, "psi": ps, "scales": scales}
    pairs = []
    old, new = [saved[m] for m in MODES]
    for h in H:
        for ex in legacy.EXPOSURES:
            s0, s1 = old["scales"][ex], new["scales"][ex]
            if s1 is None or s0 is None:
                pairs.append(
                    {
                        "lens": lens,
                        "module": "DML",
                        "variable": ex,
                        "holding_h": h,
                        "status": "DEFERRED_NO_COMMON_PAST_UNIT",
                        "n_rows": 0,
                        "n_dates": 0,
                    }
                )
                continue
            d0 = old["d"][ex].astype(float) * s0 / s1
            d1 = new["d"][ex].astype(float)
            y0 = old["y"][h]
            y1 = new["y"][h]
            ok = np.isfinite(d0) & np.isfinite(d1) & np.isfinite(y0) & np.isfinite(y1)
            a = full_est(
                np.where(ok, d0, np.nan), np.where(ok, y0, np.nan), frame.signal_date, h
            )
            b = full_est(
                np.where(ok, d1, np.nan), np.where(ok, y1, np.nan), frame.signal_date, h
            )
            pairs.append(
                {
                    "lens": lens,
                    "module": "DML",
                    "variable": ex,
                    "holding_h": h,
                    "status": "DESCRIPTIVE_MATCHED_ONLY",
                    "n_rows": int(ok.sum()),
                    "n_dates": int(frame.signal_date[ok].nunique()),
                    "legacy_same_past_unit": a["coefficient"],
                    "new_same_past_unit": b["coefficient"],
                    "new_minus_legacy": b["coefficient"] - a["coefficient"],
                    "unit": "return_fraction_per_fixed_past_SD",
                }
            )
        for state in states:
            a = old["psi"][(state, h)]
            b = new["psi"][(state, h)]
            ok = np.isfinite(a) & np.isfinite(b)
            pairs.append(
                {
                    "lens": lens,
                    "module": "AIPW",
                    "variable": state,
                    "holding_h": h,
                    "status": "DESCRIPTIVE_MATCHED_ONLY",
                    "n_rows": int(ok.sum()),
                    "n_dates": int(frame.signal_date[ok].nunique()),
                    "legacy_same_past_unit": (
                        float(a[ok].mean()) if ok.any() else math.nan
                    ),
                    "new_same_past_unit": float(b[ok].mean()) if ok.any() else math.nan,
                    "new_minus_legacy": (
                        float((b[ok] - a[ok]).mean()) if ok.any() else math.nan
                    ),
                    "unit": "return_fraction_high_minus_low",
                }
            )
    pd.DataFrame(pairs).to_csv(DATA / f"matched_comparison_{lens}.csv", index=False)
    pd.DataFrame(fits).to_csv(AUDIT / f"nuisance_{lens}.csv", index=False)
    jsave(AUDIT / f"calibration_{lens}.json", calibrations)
    replay = {}
    for kind, key in [("dml", "exposure"), ("aipw", "state_contrast")]:
        reference_path = OLD / f"data/mechanism/mechanism_tree_{kind}_{lens}.csv"
        if not reference_path.exists():
            replay[kind] = {"status": "SKIPPED_ARCHIVED_REFERENCE_UNAVAILABLE"}
            continue
        historical = pd.read_csv(reference_path)
        actual = allresults[("legacy_replay", kind)]
        m = historical.merge(
            actual, on=[key, "holding_h"], suffixes=("_historical", "_replay")
        )
        z = m[["coefficient_historical", "coefficient_replay"]].dropna()
        replay[kind] = {
            "rows": len(m),
            "complete_historical": int(
                historical.estimability_status.eq("COMPLETE").sum()
            ),
            "complete_replay": int(actual.estimability_status.eq("COMPLETE").sum()),
            "max_abs_coefficient_difference_not_reproduction_error": (
                float((z.iloc[:, 0] - z.iloc[:, 1]).abs().max()) if len(z) else None
            ),
        }
    jsave(
        AUDIT / f"complete_{lens}.json",
        {
            "lens": lens,
            "completed_at_utc": now(),
            "elapsed_seconds": time.time() - started,
            "rows": len(frame),
            "purge_violations": 0,
            "legacy_replay_comparison": replay,
        },
    )
    log(f"COMPLETE {lens}, {time.time()-started:.1f}s")


def combine():
    spec = json.loads((AUDIT / "frozen_design.json").read_text(encoding="utf8"))
    unchanged, resolutions = verify_frozen_inputs(spec["inputs"], CFG.EXP)
    summary = []
    qa = {
        "source_hashes_unchanged": unchanged,
        "frozen_input_resolution": resolutions,
        "lenses": {},
        "code_hash_unchanged": sha(__file__) == spec["code_sha256"],
    }
    for lens in LENSES:
        qa["lenses"][lens] = json.loads(
            (AUDIT / f"complete_{lens}.json").read_text(encoding="utf8")
        )
    for mode in MODES:
        for kind, expected in [("dml", 144), ("aipw", 96)]:
            f = pd.concat(
                [pd.read_csv(DATA / f"{kind}_{lens}_{mode}.csv") for lens in LENSES],
                ignore_index=True,
            )
            assert len(f) == expected
            deferred = ~f.estimability_status.eq("COMPLETE")
            assert (
                f.loc[deferred, ["coefficient", "p_holm_family", "se_hac"]]
                .isna()
                .all()
                .all()
            )
            assert (f.family_n == (24 if kind == "dml" else 32)).all()
            f.to_csv(DATA / f"{kind}_{mode}_all.csv", index=False)
            summary.append(
                {
                    "mode": mode,
                    "module": kind,
                    "grid": len(f),
                    "complete": int((~deferred).sum()),
                    "deferred": int(deferred.sum()),
                    "holm_lt_05": int((f.p_holm_family < 0.05).sum()),
                    "BH_q_lt_05_secondary": int((f.q_bh_family < 0.05).sum()),
                }
            )
    pd.DataFrame(summary).to_csv(DATA / "summary_counts.csv", index=False)
    pd.concat(
        [pd.read_csv(DATA / f"matched_comparison_{l}.csv") for l in LENSES]
    ).to_csv(DATA / "matched_comparison_all.csv", index=False)
    qa["summary"] = summary
    qa["status"] = "PASS" if qa["code_hash_unchanged"] else "CODE_CHANGED_AFTER_FREEZE"
    jsave(AUDIT / "qa_summary.json", qa)
    text = [
        "# C2: expanded-window conditional estimation",
        "",
        f"Observation cutoff: 2026-08-31. Past calibration ends before {CALIBRATION_END.date()}. Six expanding folds use the original 40% plus six equal-block algorithm. Historical hash/date sample prefix is unchanged.",
        "",
        pd.DataFrame(summary).to_markdown(index=False),
        "",
        "Unavailable estimates retain missing formal inference. S-coverage is a separate coverage-derived window. These are conditional observational associations.",
    ]
    (HERE / "SUMMARY.md").write_text("\n".join(text) + "\n", encoding="utf8")
    log("COMBINED " + json.dumps(summary))


